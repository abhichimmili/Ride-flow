-- 3. Vehicles table
CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    driver_profile_id BIGINT NOT NULL,
    registration_number VARCHAR(255) NOT NULL UNIQUE,

    brand VARCHAR(255) NOT NULL,
    model VARCHAR(255) NOT NULL,
    color VARCHAR(255),

    vehicle_type VARCHAR(255) NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_vehicles_driver_profile
        FOREIGN KEY (driver_profile_id)
        REFERENCES driver_profiles(id),

    CONSTRAINT uk_vehicle_registration_number
        UNIQUE (registration_number)
);

-- 4. Rides table
CREATE TABLE rides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL,
    driver_id BIGINT,
    vehicle_id BIGINT,

    pickup_address VARCHAR(255) NOT NULL,
    dropoff_address VARCHAR(255) NOT NULL,

    distance_km NUMERIC(8, 2) NOT NULL,
    estimated_fare NUMERIC(10, 2) NOT NULL,
    final_fare NUMERIC(10, 2),

    pickup_location geography(Point, 4326),

    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',

    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,

    CONSTRAINT fk_rides_customer
        FOREIGN KEY (customer_id)
        REFERENCES users(id),

    CONSTRAINT fk_rides_driver
        FOREIGN KEY (driver_id)
        REFERENCES driver_profiles(id),

    CONSTRAINT fk_rides_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES vehicles(id)
);